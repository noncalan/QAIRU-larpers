def build(name: str, source: Path, edits: list[Edit]) -> None:
    text = source.read_text(encoding="utf-8")
    for _, old, new, _ in edits:
        if text.count(old) != 1:
            raise ValueError(f"{name}: фрагмент должен встречаться один раз: {old!r}")
        text = text.replace(old, new)
    mutations = []
    for n, (kind, old, new, anchors) in enumerate(edits, 1):
        spans = []
        for anchor in anchors:
            pos = text.find(anchor)
            if pos < 0:
                raise ValueError(f"{name}: якорь не найден: {anchor!r}")
            spans.append([pos, pos + len(anchor)])
        mutations.append(
            {
                "id": f"{name}-{n:02d}",
                "operator": kind,
                "original": old,
                "replacement": new,
                "match_spans": spans,
            }
        )
    (HERE / f"{name}.md").write_text(text, encoding="utf-8")
    manifest = {"copy": name, "source": source.name, "mutations": mutations}
    (HERE / f"{name}.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    print(name, len(mutations))


if __name__ == "__main__":
    for name, (source, edits) in SETS.items():
        build(name, source, edits)
